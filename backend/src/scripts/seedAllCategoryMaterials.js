export async function seedAllCategoryMaterials() {
  let inserted = 0;
  let updated = 0;
  let skipped = 0;

  for (const mat of ALL_CATEGORY_MATERIALS) {
    const [existing] = await pool.query(
      'SELECT id, category_id, title FROM study_materials WHERE slug = ? OR (category_id = ? AND title = ?)',
      [mat.slug, mat.category_id, mat.title]
    );

    if (existing.length > 0) {
      // Non-destructive update to keep fields aligned
      await pool.query(
        `UPDATE study_materials SET
          title = ?, description = ?, subject = ?, category_id = ?, exam_group = ?,
          exam_name = ?, recruitment_body = ?, year = ?, language = ?, material_type = ?,
          source_url = ?, is_official = ?, status = ?
        WHERE id = ?`,
        [
          mat.title,
          mat.description,
          mat.subject,
          mat.category_id,
          mat.exam_group,
          mat.exam_name,
          mat.recruitment_body,
          mat.year,
          mat.language,
          mat.material_type,
          mat.source_url,
          mat.is_official,
          mat.status,
          existing[0].id,
        ]
      );
      updated++;
      continue;
    }

    await pool.query(
      `INSERT INTO study_materials (
        title, slug, description, subject, category_id, exam_group,
        exam_name, recruitment_body, year, language, material_type,
        source_url, is_official, status, uploaded_by, download_count
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [
        mat.title,
        mat.slug,
        mat.description,
        mat.subject,
        mat.category_id,
        mat.exam_group,
        mat.exam_name,
        mat.recruitment_body,
        mat.year,
        mat.language,
        mat.material_type,
        mat.source_url,
        mat.is_official,
        mat.status,
        mat.uploaded_by,
        mat.download_count,
      ]
    );
    inserted++;
  }

  logger.info(
    `All-category study materials seed complete: ${inserted} inserted, ${updated} updated, ${skipped} skipped. Total catalog items: ${ALL_CATEGORY_MATERIALS.length}`
  );
  return { inserted, updated, skipped, total: ALL_CATEGORY_MATERIALS.length };
}

if (process.argv[1]?.includes('seedAllCategoryMaterials.js')) {
  seedAllCategoryMaterials()
    .then((res) => {
      console.log('Result:', res);
      process.exit(0);
    })
    .catch((err) => {
      console.error('Seeding error:', err);
      process.exit(1);
    });
}
