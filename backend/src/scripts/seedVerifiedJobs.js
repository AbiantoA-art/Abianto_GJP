export async function seedVerifiedJobs() {
  let inserted = 0;
  let updated = 0;
  let skipped = 0;

  for (const job of VERIFIED_JOBS) {
    const [existing] = await pool.query(
      'SELECT id, category_id, job_group, title FROM jobs WHERE job_code = ?',
      [job.job_code]
    );

    if (existing.length > 0) {
      const current = existing[0];
      if (
        current.category_id !== job.category_id ||
        current.job_group !== job.job_group ||
        current.title !== job.title
      ) {
        await pool.query(
          `UPDATE jobs SET
            title = ?, organization = ?, department = ?, category_id = ?, job_group = ?,
            description = ?, vacancies = ?, qualification = ?, age_limit = ?, salary = ?,
            location = ?, experience = ?, application_fee = ?, opening_date = ?, last_date = ?,
            selection_process = ?, required_documents = ?, notification_url = ?, apply_url = ?,
            status = ?
          WHERE job_code = ?`,
          [
            job.title,
            job.organization,
            job.department,
            job.category_id,
            job.job_group,
            job.description,
            job.vacancies,
            job.qualification,
            job.age_limit,
            job.salary,
            job.location,
            job.experience,
            job.application_fee,
            job.opening_date,
            job.last_date,
            job.selection_process,
            job.required_documents,
            job.notification_url,
            job.apply_url,
            job.status,
            job.job_code,
          ]
        );
        updated++;
      } else {
        skipped++;
      }
      continue;
    }

    await pool.query(
      `INSERT INTO jobs (
        job_code, title, organization, department, category_id, job_group,
        description, vacancies, qualification, age_limit, salary, location,
        experience, application_fee, opening_date, last_date, selection_process,
        required_documents, notification_url, apply_url, status, created_by
      ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
      [
        job.job_code,
        job.title,
        job.organization,
        job.department,
        job.category_id,
        job.job_group,
        job.description,
        job.vacancies,
        job.qualification,
        job.age_limit,
        job.salary,
        job.location,
        job.experience,
        job.application_fee,
        job.opening_date,
        job.last_date,
        job.selection_process,
        job.required_documents,
        job.notification_url,
        job.apply_url,
        job.status,
        job.created_by,
      ]
    );
    inserted++;
  }

  logger.info(
    `Verified jobs seed complete: ${inserted} inserted, ${updated} updated, ${skipped} skipped.`
  );
  return { inserted, updated, skipped, total: VERIFIED_JOBS.length };
}

// Execute directly if run as CLI script
if (process.argv[1]?.includes('seedVerifiedJobs.js')) {
  seedVerifiedJobs()
    .then((res) => {
      console.log('Result:', res);
      process.exit(0);
    })
    .catch((err) => {
      console.error('Seeding error:', err);
      process.exit(1);
    });
}
